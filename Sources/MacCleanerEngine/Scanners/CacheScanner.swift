import Foundation

public final class CacheScanner: JunkScanner, Sendable {
    public let category: CleanCategory = .quickCache

    public init() {}

    public func scan(progress: @Sendable @escaping (String, Double) -> Void) async -> [JunkItem] {
        var items: [JunkItem] = []
        let home = NSHomeDirectory()
        let fileManager = FileManager.default

        let cachesDirectory = URL(fileURLWithPath: (home as NSString).appendingPathComponent("Library/Caches"))

        progress("Scanning User Application Caches...", 0.1)

        guard let cacheFolders = try? fileManager.contentsOfDirectory(
            at: cachesDirectory,
            includingPropertiesForKeys: [.isDirectoryKey],
            options: [.skipsHiddenFiles]
        ) else {
            return []
        }

        let total = Double(cacheFolders.count)
        for (index, folderURL) in cacheFolders.enumerated() {
            let pct = 0.1 + (Double(index) / max(1.0, total)) * 0.8
            let name = folderURL.lastPathComponent
            progress("Scanning cache: \(name)", pct)

            // Skip protected system caches
            if name.lowercased().hasPrefix("com.apple.cloud") || name.lowercased() == "cloudkit" {
                continue
            }

            let (size, count, subItems) = ScannerUtils.calculateSizeAndSubItems(url: folderURL)

            // Only surface meaningful caches (> 100 KB)
            if size > 100 * 1024 {
                let friendlyName = formatCacheName(bundleName: name)
                let subCategory = categorizeCache(bundleName: name)

                let item = JunkItem(
                    name: friendlyName,
                    path: folderURL,
                    sizeBytes: size,
                    itemCount: count,
                    category: .quickCache,
                    subCategory: subCategory,
                    isSelected: true,
                    details: "Cached network responses, images, and temporary session data.",
                    associatedApp: friendlyName,
                    subItems: subItems
                )
                items.append(item)
            }
        }

        // Check ~/.cache if exists
        let dotCache = URL(fileURLWithPath: (home as NSString).appendingPathComponent(".cache"))
        if fileManager.fileExists(atPath: dotCache.path) {
            let (size, count, subItems) = ScannerUtils.calculateSizeAndSubItems(url: dotCache)
            if size > 100 * 1024 {
                items.append(JunkItem(
                    name: "CLI Tools & User Cache (~/.cache)",
                    path: dotCache,
                    sizeBytes: size,
                    itemCount: count,
                    category: .quickCache,
                    subCategory: "Developer Tools",
                    isSelected: true,
                    details: "Caches generated by command-line utilities, pip, and dev tools.",
                    subItems: subItems
                ))
            }
        }

        // Sort descending by size
        items.sort { $0.sizeBytes > $1.sizeBytes }

        progress("Cache scan complete.", 1.0)
        return items
    }

    private func formatCacheName(bundleName: String) -> String {
        let lower = bundleName.lowercased()
        if lower.contains("google.chrome") { return "Google Chrome Cache" }
        if lower.contains("bravesoftware") || lower.contains("brave") { return "Brave Browser Cache" }
        if lower.contains("microsoft.edgemac") || lower.contains("microsoft edge") { return "Microsoft Edge Cache" }
        if lower.contains("mozilla") || lower.contains("firefox") { return "Firefox Cache" }
        if lower.contains("com.apple.safari") { return "Safari Web Cache" }
        if lower.contains("slack") { return "Slack Cache" }
        if lower.contains("discord") { return "Discord Cache" }
        if lower.contains("spotify") { return "Spotify Audio & Artwork Cache" }
        if lower.contains("homebrew") { return "Homebrew Downloads Cache" }
        if lower.contains("cocoapods") { return "CocoaPods Cache" }
        if lower.contains("org.swift.swiftpm") { return "Swift Package Manager Cache" }
        if lower.contains("quicklook") { return "macOS QuickLook Thumbnails" }
        if lower.contains("whatsapp") { return "WhatsApp Cache" }
        if lower.contains("telegram") { return "Telegram Cache" }
        if lower.contains("cursor") { return "Cursor AI Editor Cache" }
        if lower.contains("vscode") || lower.contains("code") { return "VS Code Cache" }

        // Format reverse-DNS if possible: com.foo.bar -> Foo Bar
        let parts = bundleName.split(separator: ".")
        if parts.count >= 2 {
            let cleanParts = parts.filter { !["com", "org", "net", "io", "app", "mac"].contains($0.lowercased()) }
            if !cleanParts.isEmpty {
                return cleanParts.map { $0.capitalized }.joined(separator: " ") + " Cache"
            }
        }
        return bundleName + " Cache"
    }

    private func categorizeCache(bundleName: String) -> String {
        let lower = bundleName.lowercased()
        if lower.contains("chrome") || lower.contains("safari") || lower.contains("firefox") || lower.contains("edge") || lower.contains("brave") {
            return "Web Browsers"
        }
        if lower.contains("slack") || lower.contains("discord") || lower.contains("telegram") || lower.contains("whatsapp") || lower.contains("teams") {
            return "Messaging & Communication"
        }
        if lower.contains("brew") || lower.contains("cocoapods") || lower.contains("swiftpm") || lower.contains("git") || lower.contains("code") || lower.contains("cursor") {
            return "Developer Tools"
        }
        return "Application Caches"
    }
}
