import Foundation

public final class DeepCleanScanner: JunkScanner, Sendable {
    public let category: CleanCategory = .deepClean

    public init() {}

    public func scan(progress: @Sendable @escaping (String, Double) -> Void) async -> [JunkItem] {
        var items: [JunkItem] = []
        let home = NSHomeDirectory()
        let fileManager = FileManager.default

        progress("Scanning System Logs & Diagnostic Reports...", 0.1)

        // 1. Logs & Diagnostic Reports
        let logsURL = URL(fileURLWithPath: (home as NSString).appendingPathComponent("Library/Logs"))
        if let logFolders = try? fileManager.contentsOfDirectory(at: logsURL, includingPropertiesForKeys: nil, options: [.skipsHiddenFiles]) {
            for folder in logFolders {
                let name = folder.lastPathComponent
                let (size, count, subItems) = ScannerUtils.calculateSizeAndSubItems(url: folder)
                if size > 50 * 1024 { // > 50 KB
                    let isDiag = name.contains("DiagnosticReports") || name.contains("CrashReporter")
                    items.append(JunkItem(
                        name: isDiag ? "System Diagnostic & Crash Reports" : "\(name) Logs",
                        path: folder,
                        sizeBytes: size,
                        itemCount: count,
                        category: .deepClean,
                        subCategory: "System Logs & Reports",
                        isSelected: true,
                        details: isDiag ? "Historical application crash reports and stack traces." : "Historical log outputs generated by \(name).",
                        subItems: subItems
                    ))
                }
            }
        }

        progress("Scanning Developer Junk (Xcode, Simulators, CLI)...", 0.3)

        // 2. Developer Junk
        let devTargets: [(path: String, name: String, details: String)] = [
            ("Library/Developer/Xcode/DerivedData", "Xcode DerivedData", "Intermediate build artifacts, indexes, and object files generated by Xcode."),
            ("Library/Developer/CoreSimulator/Caches", "iOS Simulator Caches", "Temporary simulator runtimes, logs, and simulated app caches."),
            ("Library/Developer/Xcode/iOS DeviceSupport", "iOS Device Support Symbols", "Debugging symbols from connected iOS devices that can be safely regenerated."),
            (".gradle/caches", "Gradle Build Caches", "Android / Java dependency downloads and build caches."),
            (".npm/_cacache", "NPM Package Cache", "Locally cached JavaScript npm packages."),
            ("Library/Caches/Yarn", "Yarn Package Cache", "Locally cached JavaScript yarn packages.")
        ]

        for target in devTargets {
            let targetURL = URL(fileURLWithPath: (home as NSString).appendingPathComponent(target.path))
            if fileManager.fileExists(atPath: targetURL.path) {
                let (size, count, subItems) = ScannerUtils.calculateSizeAndSubItems(url: targetURL)
                if size > 100 * 1024 {
                    items.append(JunkItem(
                        name: target.name,
                        path: targetURL,
                        sizeBytes: size,
                        itemCount: count,
                        category: .deepClean,
                        subCategory: "Developer Junk",
                        isSelected: true,
                        details: target.details,
                        subItems: subItems
                    ))
                }
            }
        }

        progress("Scanning Mail Attachments & Temp Downloads...", 0.6)

        // 3. Apple Mail Downloads
        let mailDownloadsURL = URL(fileURLWithPath: (home as NSString).appendingPathComponent("Library/Containers/com.apple.mail/Data/Library/Mail Downloads"))
        if fileManager.fileExists(atPath: mailDownloadsURL.path) {
            let (size, count, subItems) = ScannerUtils.calculateSizeAndSubItems(url: mailDownloadsURL)
            if size > 100 * 1024 {
                items.append(JunkItem(
                    name: "Mail Download Attachments Cache",
                    path: mailDownloadsURL,
                    sizeBytes: size,
                    itemCount: count,
                    category: .deepClean,
                    subCategory: "Mail & Documents",
                    isSelected: false, // Default false so user can review
                    details: "Cached copies of email attachments opened in Apple Mail.",
                    subItems: subItems
                ))
            }
        }

        // 4. Saved Application States
        let savedStateURL = URL(fileURLWithPath: (home as NSString).appendingPathComponent("Library/Saved Application State"))
        if let states = try? fileManager.contentsOfDirectory(at: savedStateURL, includingPropertiesForKeys: nil, options: [.skipsHiddenFiles]) {
            var stateSize: Int64 = 0
            var stateCount = 0
            var stateSubs: [JunkSubItem] = []

            for state in states {
                let (size, count, subItems) = ScannerUtils.calculateSizeAndSubItems(url: state)
                stateSize += size
                stateCount += count
                stateSubs.append(contentsOf: subItems)
            }

            if stateSize > 50 * 1024 {
                items.append(JunkItem(
                    name: "Saved Application States",
                    path: savedStateURL,
                    sizeBytes: stateSize,
                    itemCount: stateCount,
                    category: .deepClean,
                    subCategory: "Residual App State",
                    isSelected: true,
                    details: "Window states and restored tabs from previous app sessions.",
                    subItems: stateSubs
                ))
            }
        }

        progress("Scanning System Trash Bin...", 0.8)

        // 5. Trash Bin
        let trashURL = URL(fileURLWithPath: (home as NSString).appendingPathComponent(".Trash"))
        if fileManager.fileExists(atPath: trashURL.path) {
            let (size, count, subItems) = ScannerUtils.calculateSizeAndSubItems(url: trashURL)
            if size > 0 || count > 0 {
                items.append(JunkItem(
                    name: "System Trash Bin",
                    path: trashURL,
                    sizeBytes: size,
                    itemCount: count,
                    category: .deepClean,
                    subCategory: "Trash",
                    isSelected: true,
                    details: "\(count) deleted items currently resting in the macOS Trash.",
                    subItems: subItems
                ))
            }
        }

        // 6. Incomplete Downloads
        let downloadsURL = URL(fileURLWithPath: (home as NSString).appendingPathComponent("Downloads"))
        if let downloads = try? fileManager.contentsOfDirectory(at: downloadsURL, includingPropertiesForKeys: [.fileSizeKey], options: [.skipsHiddenFiles]) {
            var incompleteSize: Int64 = 0
            var incompleteCount = 0
            var incompleteSubs: [JunkSubItem] = []

            for file in downloads {
                let ext = file.pathExtension.lowercased()
                if ["crdownload", "download", "part"].contains(ext) {
                    if let values = try? file.resourceValues(forKeys: [.fileSizeKey]),
                       let size = values.fileSize {
                        incompleteSize += Int64(size)
                        incompleteCount += 1
                        incompleteSubs.append(JunkSubItem(name: file.lastPathComponent, path: file, sizeBytes: Int64(size)))
                    }
                }
            }

            if incompleteCount > 0 {
                items.append(JunkItem(
                    name: "Incomplete / Broken Downloads",
                    path: downloadsURL,
                    sizeBytes: incompleteSize,
                    itemCount: incompleteCount,
                    category: .deepClean,
                    subCategory: "Downloads Junk",
                    isSelected: true,
                    details: "Unfinished browser and torrent downloads (.crdownload, .part).",
                    subItems: incompleteSubs
                ))
            }
        }

        items.sort { $0.sizeBytes > $1.sizeBytes }
        progress("Deep clean scan complete.", 1.0)
        return items
    }
}
